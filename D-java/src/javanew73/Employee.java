package javanew73;

public class Employee {
	private String employeeId;
	private String name;

	public String getEmployeeId() {
		return employeeId;
	}

	public String getName() {
		return name;

	}

	public void setEmployeeId(String Id) {
		this.employeeId = Id;
	}

	public void setName(String name) {
		this.name = name;
	}

	
}
